#!/usr/bin/env python3
"""Deterministic IP-03 full-source manifest and optional exact input diff.

Run at source root after all edits and before packing. The manifest and its
checksum list intentionally exclude their own content to avoid a self-hash loop.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import stat

ROOT = Path(__file__).resolve().parents[3]
BASE = Path('docs/cue_parallel_ip01/ip03_verification')
EXCLUDED = {str(BASE / 'SOURCE_MANIFEST.json'), str(BASE / 'SHA256SUMS')}


def scan(root):
    entries = {}
    for path in sorted(root.rglob('*')):
        # A symlink to a directory is still a source entry and must be hashed
        # as a symlink, not dropped because Path.is_dir follows its target.
        if path.is_dir() and not path.is_symlink():
            continue
        rel = path.relative_to(root).as_posix()
        if rel in EXCLUDED:
            continue
        mode = stat.S_IMODE(path.lstat().st_mode)
        if path.is_symlink():
            target = os.readlink(path)
            entries[rel] = {'type': 'symlink', 'target': target, 'mode': oct(mode),
                            'sha256': hashlib.sha256(os.fsencode(target)).hexdigest()}
        elif path.is_file():
            entries[rel] = {'type': 'file', 'mode': oct(mode),
                            'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}
        else:
            raise ValueError(f'unexpected file type: {rel}')
    return entries


def make_diff(old, new):
    prev, now = set(old), set(new)
    return {
        'added': {k: new[k] for k in sorted(now - prev)},
        'removed': {k: old[k] for k in sorted(prev - now)},
        'changed': {k: {'old': old[k], 'new': new[k]} for k in sorted(prev & now) if old[k] != new[k]},
        'unchanged_count': sum(1 for k in prev & now if old[k] == new[k]),
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--baseline', type=Path, help='extracted baseline tonepoet/ root')
    args = parser.parse_args()
    if args.baseline:
        if not args.baseline.is_dir():
            parser.error('--baseline must be extracted tonepoet source root')
        old = scan(args.baseline)
        current = scan(ROOT)
        # The diff itself is generated by this tool, so exclude it from the
        # old-vs-current report rather than trying to hash a report about itself.
        diff_path = str(BASE / 'SOURCE_DIFF.json')
        old.pop(diff_path, None)
        current.pop(diff_path, None)
        diff = make_diff(old, current)
        (ROOT / diff_path).write_text(json.dumps(diff, indent=2, sort_keys=True) + '\n')
    entries = scan(ROOT)
    canonical = json.dumps(entries, sort_keys=True, separators=(',', ':')).encode()
    manifest = {
        'input_name': 'TonePoet_SNAPSHOT_d8c25d3_2026-10-24.tar.gz',
        'input_archive_sha256': 'fa51a09ad0c71fe17564053c8fd309f38bb5592730bb80fbac29dcc9e519fd95',
        'reported_input_commit': 'd8c25d3 (from supplied identity letter; .git absent)',
        'entry_count': len(entries),
        'source_tree_sha256': hashlib.sha256(canonical).hexdigest(),
        'excluded_self_hashes': sorted(EXCLUDED),
        'entries': entries,
    }
    manifest_file = ROOT / BASE / 'SOURCE_MANIFEST.json'
    manifest_file.write_text(json.dumps(manifest, indent=2, sort_keys=True) + '\n')
    entries_with_manifest = dict(entries)
    entries_with_manifest[str(BASE / 'SOURCE_MANIFEST.json')] = {
        'sha256': hashlib.sha256(manifest_file.read_bytes()).hexdigest(),
        'type': 'file', 'mode': oct(stat.S_IMODE(manifest_file.stat().st_mode)),
    }
    sums = ''.join(f"{info['sha256']}  {path}\n" for path, info in sorted(entries_with_manifest.items()) if info['type'] == 'file')
    (ROOT / BASE / 'SHA256SUMS').write_text(sums)
    print(json.dumps({'entry_count': len(entries), 'source_tree_sha256': manifest['source_tree_sha256'],
                      'hashed_regular_files': len(sums.splitlines()),
                      'manifest': str(BASE / 'SOURCE_MANIFEST.json')}))


if __name__ == '__main__':
    main()
