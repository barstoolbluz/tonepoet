fn parse_album_from_directory_name(output_dir: &Path) -> (String, String, Option<String>) {
    // Parse directory name: "Artist - Album (Year) [Format] {Pressing} [Uploader]"
    let dir_name = output_dir
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("Unknown Album");

    // TODO: Implement robust parsing
    // For now, basic fallback
    if let Some(dash_pos) = dir_name.find(" - ") {
        let artist = dir_name[..dash_pos].to_string();
        let rest = &dir_name[dash_pos + 3..];

        // Extract album title (before year parentheses)
        let album = if let Some(paren_pos) = rest.find(" (") {
            rest[..paren_pos].to_string()
        } else {
            rest.to_string()
        };

        // Extract year if present
        let year = if let Some(year_start) = rest.find(" (") {
            if let Some(year_end) = rest[year_start..].find(")") {
                let year_part = &rest[year_start + 2..year_start + year_end];
                Some(year_part.to_string())
            } else {
                None
            }
        } else {
            None
        };

        (artist, album, year)
    } else {
        ("Unknown Artist".to_string(), dir_name.to_string(), None)
    }
}

fn fallback_track_metadata(
    file_path: &PathBuf,
    track_number: u32,
    album_artist: &str,
) -> TrackMetadata {
    // Parse filename: "01 - Track Name.ext"
    let filename = file_path
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("Unknown Track");

    let format = AudioFormat::from_extension(
        file_path
            .extension()
            .and_then(|e| e.to_str())
            .unwrap_or("flac"),
    )
    .unwrap_or(AudioFormat::Flac);

    // Parse track title from filename
    let title = if let Some(dash_pos) = filename.find(" - ") {
        let title_part = &filename[dash_pos + 3..];
        // Remove extension
        if let Some(dot_pos) = title_part.rfind('.') {
            title_part[..dot_pos].to_string()
        } else {
            title_part.to_string()
        }
    } else {
        format!("Track {:02}", track_number)
    };

    TrackMetadata {
        number: track_number,
        title,
        artist: album_artist.to_string(),
        filename: filename.to_string(),
        format,
        duration: None, // TODO: Extract from file
        replaygain_track_gain: None,
        replaygain_track_peak: None,
        replaygain_album_gain: None,
        replaygain_album_peak: None,
    }
}

fn escape_cue_string(s: &str) -> String {
    // Escape quotes and backslashes for cue file format
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn sanitize_filename(filename: &str) -> String {
    // Remove/replace invalid filename characters
    filename
        .chars()
        .map(|c| match c {
            '/' | '\\' | ':' | '*' | '?' | '"' | '<' | '>' | '|' => '_',
            _ => c,
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_audio_format_detection() {
        assert_eq!(AudioFormat::from_extension("flac"), Some(AudioFormat::Flac));
        assert_eq!(AudioFormat::from_extension("OPUS"), Some(AudioFormat::Opus));
        assert_eq!(AudioFormat::from_extension("mp3"), Some(AudioFormat::Mp3));
    }

    #[test]
    fn test_cue_format_strings() {
        assert_eq!(AudioFormat::Opus.cue_format(), "OPUS");
        assert_eq!(AudioFormat::Mp3.cue_format(), "MP3");
        assert_eq!(AudioFormat::Flac.cue_format(), "FLAC");
    }

    #[test]
    fn test_filename_sanitization() {
        assert_eq!(sanitize_filename("Album: The Movie"), "Album_ The Movie");
        assert_eq!(sanitize_filename("Track \"Name\""), "Track _Name_");
    }

    #[test]
    fn test_cue_string_escaping() {
        assert_eq!(escape_cue_string("Song \"Title\""), "Song \\\"Title\\\"");
        assert_eq!(escape_cue_string("Path\\File"), "Path\\\\File");
    }

    #[test]
    fn test_directory_name_parsing() {
        let (artist, album, year) = parse_album_from_directory_name(Path::new(
            "Artist - Album Title (1995) [FLAC] {Pressing} [Uploader]",
        ));
        assert_eq!(artist, "Artist");
        assert_eq!(album, "Album Title");
        assert_eq!(year, Some("1995".to_string()));
    }
}
